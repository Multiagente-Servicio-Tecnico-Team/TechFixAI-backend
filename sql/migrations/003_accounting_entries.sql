CREATE TABLE IF NOT EXISTS accounting_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_number BIGINT GENERATED ALWAYS AS IDENTITY UNIQUE NOT NULL,
    operation_date DATE NOT NULL,
    concept VARCHAR(200) NOT NULL CHECK (char_length(btrim(concept)) BETWEEN 1 AND 200),
    detail TEXT NOT NULL CHECK (char_length(btrim(detail)) BETWEEN 1 AND 4000),
    category_id BIGINT NOT NULL REFERENCES accounting_categories(id) ON DELETE RESTRICT,
    currency CHAR(3) NOT NULL DEFAULT 'PEN' CHECK (currency = 'PEN'),
    debit_total NUMERIC(14,2) NOT NULL CHECK (debit_total > 0),
    credit_total NUMERIC(14,2) NOT NULL CHECK (credit_total > 0),
    status VARCHAR(10) NOT NULL DEFAULT 'CONFIRMED' CHECK (status IN ('CONFIRMED', 'REVERSED')),
    responsible_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    idempotency_key UUID,
    request_hash CHAR(64),
    reversal_of_entry_id BIGINT UNIQUE REFERENCES accounting_entries(id) ON DELETE RESTRICT,
    reversal_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reversed_at TIMESTAMPTZ,
    CONSTRAINT accounting_entry_idempotency_pair CHECK (
        (idempotency_key IS NULL AND request_hash IS NULL) OR
        (idempotency_key IS NOT NULL AND request_hash IS NOT NULL AND request_hash ~ '^[0-9a-f]{64}$')
    ),
    CONSTRAINT accounting_entry_reversal_reason CHECK (
        (reversal_of_entry_id IS NULL AND reversal_reason IS NULL) OR
        (reversal_of_entry_id IS NOT NULL AND reversal_reason IS NOT NULL AND char_length(btrim(reversal_reason)) BETWEEN 1 AND 2000)
    ),
    CONSTRAINT accounting_entry_not_self_reversal CHECK (reversal_of_entry_id IS NULL OR reversal_of_entry_id <> id),
    CONSTRAINT accounting_entry_reversed_timestamp CHECK (
        (status = 'CONFIRMED' AND reversed_at IS NULL) OR
        (status = 'REVERSED' AND reversed_at IS NOT NULL)
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_accounting_entries_actor_idempotency
    ON accounting_entries (responsible_user_id, idempotency_key)
    WHERE idempotency_key IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_accounting_entries_date_number
    ON accounting_entries (operation_date DESC, entry_number DESC);
CREATE INDEX IF NOT EXISTS ix_accounting_entries_category ON accounting_entries (category_id);
CREATE INDEX IF NOT EXISTS ix_accounting_entries_status ON accounting_entries (status);
CREATE INDEX IF NOT EXISTS ix_accounting_entries_responsible ON accounting_entries (responsible_user_id);

CREATE TABLE IF NOT EXISTS accounting_entry_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id BIGINT NOT NULL REFERENCES accounting_entries(id) ON DELETE RESTRICT,
    line_number SMALLINT NOT NULL CHECK (line_number BETWEEN 1 AND 100),
    account_code VARCHAR(40) NOT NULL CHECK (char_length(btrim(account_code)) BETWEEN 1 AND 40),
    account_name VARCHAR(200) NOT NULL CHECK (char_length(btrim(account_name)) BETWEEN 1 AND 200),
    description TEXT CHECK (description IS NULL OR char_length(description) <= 1000),
    debit NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (debit >= 0),
    credit NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (credit >= 0),
    CONSTRAINT ux_accounting_entry_line_number UNIQUE (entry_id, line_number),
    CONSTRAINT accounting_entry_line_one_side CHECK ((debit > 0) <> (credit > 0))
);
CREATE INDEX IF NOT EXISTS ix_accounting_entry_lines_entry ON accounting_entry_lines (entry_id, line_number);

CREATE TABLE IF NOT EXISTS accounting_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id BIGINT NOT NULL REFERENCES accounting_entries(id) ON DELETE RESTRICT,
    actor_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    event_type VARCHAR(24) NOT NULL CHECK (event_type IN ('ENTRY_CREATED', 'ENTRY_REVERSED', 'REVERSAL_CREATED')),
    related_entry_id BIGINT REFERENCES accounting_entries(id) ON DELETE RESTRICT,
    reason TEXT CHECK (reason IS NULL OR char_length(reason) <= 2000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ux_accounting_audit_entry_event UNIQUE (entry_id, event_type),
    CONSTRAINT accounting_audit_event_shape CHECK (
        (event_type = 'ENTRY_CREATED' AND related_entry_id IS NULL AND reason IS NULL) OR
        (event_type IN ('ENTRY_REVERSED', 'REVERSAL_CREATED') AND related_entry_id IS NOT NULL AND reason IS NOT NULL)
    )
);
CREATE INDEX IF NOT EXISTS ix_accounting_audit_timeline ON accounting_audit_events (entry_id, created_at, id);

CREATE OR REPLACE FUNCTION accounting_reject_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Accounting history is immutable' USING ERRCODE = '55000';
END;
$$;

CREATE OR REPLACE FUNCTION accounting_guard_entry_update() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Accounting entries cannot be deleted' USING ERRCODE = '55000';
    END IF;
    IF ROW(NEW.entry_number, NEW.operation_date, NEW.concept, NEW.detail, NEW.category_id,
           NEW.currency, NEW.debit_total, NEW.credit_total, NEW.responsible_user_id,
           NEW.idempotency_key, NEW.request_hash, NEW.reversal_of_entry_id,
           NEW.reversal_reason, NEW.created_at)
       IS DISTINCT FROM
       ROW(OLD.entry_number, OLD.operation_date, OLD.concept, OLD.detail, OLD.category_id,
           OLD.currency, OLD.debit_total, OLD.credit_total, OLD.responsible_user_id,
           OLD.idempotency_key, OLD.request_hash, OLD.reversal_of_entry_id,
           OLD.reversal_reason, OLD.created_at) THEN
        RAISE EXCEPTION 'Accounting entry fields are immutable' USING ERRCODE = '55000';
    END IF;
    IF OLD.status <> 'CONFIRMED' OR NEW.status <> 'REVERSED' OR OLD.reversed_at IS NOT NULL OR
       NEW.reversed_at IS NULL OR NEW.updated_at IS NULL OR NEW.updated_at < OLD.updated_at THEN
        RAISE EXCEPTION 'Invalid accounting status transition' USING ERRCODE = '55000';
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION accounting_check_entry_balance() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    target_id BIGINT;
    entry_row accounting_entries%ROWTYPE;
    line_count BIGINT;
    debit_sum NUMERIC(14,2);
    credit_sum NUMERIC(14,2);
BEGIN
    IF TG_TABLE_NAME = 'accounting_entry_lines' THEN
        target_id := COALESCE(NEW.entry_id, OLD.entry_id);
    ELSE
        target_id := COALESCE(NEW.id, OLD.id);
    END IF;
    SELECT * INTO entry_row FROM accounting_entries WHERE id = target_id;
    IF NOT FOUND THEN
        RETURN NULL;
    END IF;
    SELECT count(*), COALESCE(sum(debit), 0), COALESCE(sum(credit), 0)
      INTO line_count, debit_sum, credit_sum
      FROM accounting_entry_lines WHERE entry_id = target_id;
    IF line_count < 2 OR line_count > 100 OR
       debit_sum <= 0 OR debit_sum <> credit_sum OR
       debit_sum <> entry_row.debit_total OR credit_sum <> entry_row.credit_total THEN
        RAISE EXCEPTION 'Accounting entry lines do not balance' USING ERRCODE = '23514';
    END IF;
    IF entry_row.status = 'REVERSED' AND NOT EXISTS (
        SELECT 1 FROM accounting_entries reversal WHERE reversal.reversal_of_entry_id = target_id
    ) THEN
        RAISE EXCEPTION 'Reversed entry requires a reversal record' USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS accounting_entries_immutable ON accounting_entries;
CREATE TRIGGER accounting_entries_immutable BEFORE UPDATE OR DELETE ON accounting_entries
    FOR EACH ROW EXECUTE FUNCTION accounting_guard_entry_update();
DROP TRIGGER IF EXISTS accounting_lines_immutable ON accounting_entry_lines;
CREATE TRIGGER accounting_lines_immutable BEFORE UPDATE OR DELETE ON accounting_entry_lines
    FOR EACH ROW EXECUTE FUNCTION accounting_reject_mutation();
DROP TRIGGER IF EXISTS accounting_audit_append_only ON accounting_audit_events;
CREATE TRIGGER accounting_audit_append_only BEFORE UPDATE OR DELETE ON accounting_audit_events
    FOR EACH ROW EXECUTE FUNCTION accounting_reject_mutation();

DROP TRIGGER IF EXISTS accounting_balance_after_entry ON accounting_entries;
CREATE CONSTRAINT TRIGGER accounting_balance_after_entry
    AFTER INSERT OR UPDATE ON accounting_entries DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION accounting_check_entry_balance();
DROP TRIGGER IF EXISTS accounting_balance_after_line ON accounting_entry_lines;
CREATE CONSTRAINT TRIGGER accounting_balance_after_line
    AFTER INSERT ON accounting_entry_lines DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION accounting_check_entry_balance();

COMMIT;
