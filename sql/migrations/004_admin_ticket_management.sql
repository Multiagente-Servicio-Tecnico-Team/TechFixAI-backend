-- Adiciona origen/contacto para tickets administrativos y auditoria append-only.
BEGIN;

ALTER TABLE tickets ALTER COLUMN customer_id DROP NOT NULL;
ALTER TABLE tickets ADD COLUMN IF NOT EXISTS origin VARCHAR(10);
ALTER TABLE tickets ADD COLUMN IF NOT EXISTS contact_name VARCHAR(200);
ALTER TABLE tickets ADD COLUMN IF NOT EXISTS contact_phone VARCHAR(20);
ALTER TABLE tickets ADD COLUMN IF NOT EXISTS contact_email VARCHAR(255);
ALTER TABLE tickets ADD COLUMN IF NOT EXISTS advance_amount NUMERIC(10,2);
ALTER TABLE tickets ADD COLUMN IF NOT EXISTS advance_payment_method VARCHAR(12);

DO $$ BEGIN
  ALTER TABLE tickets ADD CONSTRAINT chk_tickets_origin
    CHECK (origin IS NULL OR origin IN ('MANUAL', 'ONLINE'));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
  ALTER TABLE tickets ADD CONSTRAINT chk_tickets_advance
    CHECK ((advance_amount IS NULL AND advance_payment_method IS NULL) OR
           (advance_amount > 0 AND advance_payment_method IN ('YAPE_PLIN', 'CASH', 'CARD')));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
  ALTER TABLE tickets ADD CONSTRAINT chk_tickets_origin_customer
    CHECK (origin IS NULL OR (origin = 'MANUAL' AND contact_name IS NOT NULL AND contact_phone IS NOT NULL)
                     OR (origin = 'ONLINE' AND customer_id IS NOT NULL));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

CREATE TABLE IF NOT EXISTS ticket_audit_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id BIGINT NOT NULL REFERENCES tickets(id) ON DELETE RESTRICT,
  actor_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  event_type VARCHAR(20) NOT NULL CHECK (event_type IN ('CREATED','UPDATED','STATUS_CHANGED','CANCELLED','QUOTE_CREATED')),
  changed_fields JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_ticket_audit_ticket_created
  ON ticket_audit_events(ticket_id, created_at, id);

COMMIT;
