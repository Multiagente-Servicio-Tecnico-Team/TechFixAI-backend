-- Compras recibidas, recepciones y movimientos auditables. Migración aditiva.
-- Aplicar solamente en una base existente autorizada y con respaldo verificado.
BEGIN;

ALTER TABLE suppliers ALTER COLUMN name TYPE VARCHAR(200);
ALTER TABLE suppliers ALTER COLUMN phone TYPE VARCHAR(30);
ALTER TABLE suppliers ADD COLUMN IF NOT EXISTS tax_id VARCHAR(20);
ALTER TABLE suppliers ADD COLUMN IF NOT EXISTS contact_name VARCHAR(200);
ALTER TABLE suppliers ADD COLUMN IF NOT EXISTS address TEXT;

CREATE UNIQUE INDEX IF NOT EXISTS ux_suppliers_tax_id
    ON suppliers (upper(btrim(tax_id)))
    WHERE tax_id IS NOT NULL AND btrim(tax_id) <> '';

CREATE TABLE IF NOT EXISTS supplier_purchases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id BIGINT NOT NULL REFERENCES suppliers(id) ON DELETE RESTRICT,
    purchase_order_id BIGINT REFERENCES purchase_orders(id) ON DELETE RESTRICT,
    supplier_name_snapshot VARCHAR(200) NOT NULL,
    supplier_tax_id_snapshot VARCHAR(20),
    document_type VARCHAR(30) NOT NULL CHECK (char_length(btrim(document_type)) BETWEEN 1 AND 30),
    document_series VARCHAR(30),
    document_number VARCHAR(40) NOT NULL CHECK (char_length(btrim(document_number)) BETWEEN 1 AND 40),
    issue_date DATE NOT NULL,
    due_date DATE,
    currency CHAR(3) NOT NULL DEFAULT 'PEN' CHECK (currency = 'PEN'),
    subtotal NUMERIC(14,2) NOT NULL CHECK (subtotal >= 0),
    tax_total NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (tax_total >= 0),
    discount_total NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (discount_total >= 0),
    other_charges NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (other_charges >= 0),
    total_amount NUMERIC(14,2) NOT NULL CHECK (total_amount >= 0),
    payment_method VARCHAR(20) NOT NULL CHECK (payment_method IN ('TRANSFER','CASH','CARD','OTHER')),
    payment_status VARCHAR(10) NOT NULL CHECK (payment_status IN ('PENDING','PAID')),
    status VARCHAR(24) NOT NULL DEFAULT 'REGISTERED'
        CHECK (status IN ('REGISTERED','PARTIALLY_RECEIVED','RECEIVED','CANCELLED')),
    notes TEXT,
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_supplier_purchase_due_date CHECK (due_date IS NULL OR due_date >= issue_date)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_supplier_purchase_document
    ON supplier_purchases (supplier_id, upper(btrim(document_type)), upper(btrim(coalesce(document_series,''))), upper(btrim(document_number)))
    WHERE status <> 'CANCELLED';
CREATE INDEX IF NOT EXISTS ix_supplier_purchases_supplier_date
    ON supplier_purchases (supplier_id, issue_date DESC, id DESC);
CREATE INDEX IF NOT EXISTS ix_supplier_purchases_status_date
    ON supplier_purchases (status, issue_date DESC, id DESC);
CREATE INDEX IF NOT EXISTS ix_supplier_purchases_payment_status
    ON supplier_purchases (payment_status, issue_date DESC, id DESC);

CREATE TABLE IF NOT EXISTS supplier_purchase_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id BIGINT NOT NULL REFERENCES supplier_purchases(id) ON DELETE RESTRICT,
    spare_part_id BIGINT REFERENCES spare_parts(id) ON DELETE SET NULL,
    code_snapshot VARCHAR(50),
    description_snapshot VARCHAR(300) NOT NULL CHECK (char_length(btrim(description_snapshot)) BETWEEN 1 AND 300),
    quantity NUMERIC(12,3) NOT NULL CHECK (quantity > 0),
    unit_cost NUMERIC(14,2) NOT NULL CHECK (unit_cost >= 0),
    discount_amount NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    tax_amount NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (tax_amount >= 0),
    line_total NUMERIC(14,2) NOT NULL CHECK (line_total >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_supplier_purchase_items_purchase
    ON supplier_purchase_items (purchase_id, id);

CREATE TABLE IF NOT EXISTS purchase_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id BIGINT NOT NULL REFERENCES supplier_purchases(id) ON DELETE RESTRICT,
    actor_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    idempotency_key UUID NOT NULL,
    request_hash CHAR(64) NOT NULL CHECK (request_hash ~ '^[0-9a-f]{64}$'),
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    notes TEXT,
    CONSTRAINT uq_purchase_receipt_actor_key UNIQUE (purchase_id, actor_user_id, idempotency_key)
);
CREATE INDEX IF NOT EXISTS ix_purchase_receipts_purchase
    ON purchase_receipts (purchase_id, received_at, id);

CREATE TABLE IF NOT EXISTS purchase_receipt_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id BIGINT NOT NULL REFERENCES purchase_receipts(id) ON DELETE RESTRICT,
    purchase_item_id BIGINT NOT NULL REFERENCES supplier_purchase_items(id) ON DELETE RESTRICT,
    quantity_received NUMERIC(12,3) NOT NULL CHECK (quantity_received > 0),
    CONSTRAINT uq_purchase_receipt_line UNIQUE (receipt_id, purchase_item_id)
);
CREATE INDEX IF NOT EXISTS ix_purchase_receipt_items_purchase_item
    ON purchase_receipt_items (purchase_item_id, id);

CREATE TABLE IF NOT EXISTS inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    spare_part_id BIGINT REFERENCES spare_parts(id) ON DELETE SET NULL,
    purchase_receipt_item_id BIGINT NOT NULL UNIQUE REFERENCES purchase_receipt_items(id) ON DELETE RESTRICT,
    movement_type VARCHAR(20) NOT NULL CHECK (movement_type = 'PURCHASE_RECEIPT'),
    code_snapshot VARCHAR(50) NOT NULL,
    name_snapshot VARCHAR(150) NOT NULL,
    quantity_delta INT NOT NULL CHECK (quantity_delta > 0),
    stock_before INT NOT NULL CHECK (stock_before >= 0),
    stock_after INT NOT NULL CHECK (stock_after = stock_before + quantity_delta),
    actor_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_inventory_movements_part_date
    ON inventory_movements (spare_part_id, created_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS supplier_purchase_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id BIGINT NOT NULL REFERENCES supplier_purchases(id) ON DELETE RESTRICT,
    actor_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    event_type VARCHAR(30) NOT NULL CHECK (event_type IN ('CREATED','UPDATED','RECEIPT_CONFIRMED','PAYMENT_STATUS_CHANGED','CANCELLED')),
    changed_fields JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_supplier_purchase_audit_date
    ON supplier_purchase_audit_events (purchase_id, created_at, id);

COMMIT;
