CREATE TABLE IF NOT EXISTS public.schema_migrations (
    version VARCHAR(3) PRIMARY KEY CHECK (version ~ '^[0-9]{3}$'),
    filename VARCHAR(200) NOT NULL,
    checksum CHAR(64) NOT NULL CHECK (checksum ~ '^[0-9a-f]{64}$'),
    verified_by VARCHAR(120) NOT NULL CHECK (char_length(btrim(verified_by)) BETWEEN 1 AND 120),
    applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name VARCHAR(200) NOT NULL CHECK (char_length(btrim(display_name)) BETWEEN 2 AND 200),
    phone VARCHAR(30) NOT NULL CHECK (char_length(btrim(phone)) BETWEEN 7 AND 30),
    email VARCHAR(255),
    origin VARCHAR(10) NOT NULL CHECK (origin IN ('MANUAL', 'PORTAL')),
    user_id BIGINT UNIQUE REFERENCES public.users(id) ON DELETE RESTRICT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by_user_id BIGINT REFERENCES public.users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_customers_portal_link CHECK (origin <> 'PORTAL' OR user_id IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS ix_customers_display_name ON public.customers (lower(display_name), id);
CREATE INDEX IF NOT EXISTS ix_customers_phone ON public.customers (phone);
CREATE INDEX IF NOT EXISTS ix_customers_email ON public.customers (lower(email)) WHERE email IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.customer_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES public.customers(id) ON DELETE RESTRICT,
    actor_user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    event_type VARCHAR(30) NOT NULL CHECK (event_type IN ('CREATED', 'UPDATED', 'ACCOUNT_LINKED', 'DEACTIVATED')),
    changed_fields JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_customer_audit_customer_date
    ON public.customer_audit_events (customer_id, created_at, id);

