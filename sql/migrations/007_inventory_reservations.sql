-- Reservas de inventario y pedidos para cotizaciones de venta directa.
-- Ejecutar solo después de reconciliar y respaldar la base destino.
BEGIN;

ALTER TABLE public.payments ALTER COLUMN ticket_id DROP NOT NULL;
ALTER TABLE public.payments ALTER COLUMN customer_id DROP NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ux_payments_idempotency_key
    ON public.payments (idempotency_key) WHERE idempotency_key IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.inventory_reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_id BIGINT NOT NULL UNIQUE REFERENCES public.quotes(id) ON DELETE RESTRICT,
    customer_id BIGINT NOT NULL REFERENCES public.customers(id) ON DELETE RESTRICT,
    idempotency_key VARCHAR(200) NOT NULL,
    status VARCHAR(12) NOT NULL CHECK (status IN ('RESERVED', 'RELEASED', 'CONSUMED')),
    expires_at TIMESTAMPTZ NOT NULL,
    accepted_by_user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    accepted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    released_by_user_id BIGINT REFERENCES public.users(id) ON DELETE RESTRICT,
    released_at TIMESTAMPTZ,
    release_reason VARCHAR(30) CHECK (release_reason IS NULL OR release_reason IN ('REJECTED', 'CANCELLED', 'EXPIRED')),
    consumed_at TIMESTAMPTZ,
    CONSTRAINT chk_inventory_reservation_terminal CHECK (
      (status = 'RESERVED' AND released_at IS NULL AND consumed_at IS NULL) OR
      (status = 'RELEASED' AND released_at IS NOT NULL AND consumed_at IS NULL) OR
      (status = 'CONSUMED' AND released_at IS NULL AND consumed_at IS NOT NULL)
    )
);
CREATE INDEX IF NOT EXISTS ix_inventory_reservations_active_expiry
    ON public.inventory_reservations (expires_at, quote_id) WHERE status = 'RESERVED';

CREATE TABLE IF NOT EXISTS public.inventory_reservation_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL REFERENCES public.inventory_reservations(id) ON DELETE RESTRICT,
    quote_detail_id BIGINT NOT NULL UNIQUE REFERENCES public.quote_details(id) ON DELETE RESTRICT,
    spare_part_id BIGINT NOT NULL REFERENCES public.spare_parts(id) ON DELETE RESTRICT,
    code_snapshot VARCHAR(50) NOT NULL,
    name_snapshot VARCHAR(150) NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10,2) NOT NULL CHECK (unit_price > 0),
    subtotal NUMERIC(12,2) NOT NULL CHECK (subtotal = unit_price * quantity)
);
CREATE INDEX IF NOT EXISTS ix_inventory_reservation_items_part
    ON public.inventory_reservation_items (spare_part_id, reservation_id);

CREATE TABLE IF NOT EXISTS public.sales_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    quote_id BIGINT NOT NULL UNIQUE REFERENCES public.quotes(id) ON DELETE RESTRICT,
    payment_id BIGINT NOT NULL UNIQUE REFERENCES public.payments(id) ON DELETE RESTRICT,
    customer_id BIGINT NOT NULL REFERENCES public.customers(id) ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PAID', 'PREPARING', 'FULFILLED', 'CANCELLED')),
    total_amount NUMERIC(10,2) NOT NULL CHECK (total_amount > 0),
    customer_name_snapshot VARCHAR(200) NOT NULL,
    customer_phone_snapshot VARCHAR(30) NOT NULL,
    customer_email_snapshot VARCHAR(255),
    created_by_user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_sales_orders_customer_created
    ON public.sales_orders (customer_id, created_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS public.sales_order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sales_order_id BIGINT NOT NULL REFERENCES public.sales_orders(id) ON DELETE RESTRICT,
    quote_detail_id BIGINT NOT NULL UNIQUE REFERENCES public.quote_details(id) ON DELETE RESTRICT,
    spare_part_id BIGINT REFERENCES public.spare_parts(id) ON DELETE SET NULL,
    code_snapshot VARCHAR(50),
    name_snapshot VARCHAR(150) NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10,2) NOT NULL CHECK (unit_price > 0),
    subtotal NUMERIC(12,2) NOT NULL CHECK (subtotal = unit_price * quantity)
);

ALTER TABLE public.logistics_records ALTER COLUMN ticket_id DROP NOT NULL;
ALTER TABLE public.logistics_records ADD COLUMN IF NOT EXISTS sales_order_id BIGINT;
ALTER TABLE public.logistics_records ADD COLUMN IF NOT EXISTS commercial_customer_id BIGINT;
ALTER TABLE public.logistics_records ADD COLUMN IF NOT EXISTS created_by_user_id BIGINT;
DO $$ BEGIN
  ALTER TABLE public.logistics_records ADD CONSTRAINT fk_logistics_sales_order
    FOREIGN KEY (sales_order_id) REFERENCES public.sales_orders(id) ON DELETE RESTRICT;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
  ALTER TABLE public.logistics_records ADD CONSTRAINT fk_logistics_commercial_customer
    FOREIGN KEY (commercial_customer_id) REFERENCES public.customers(id) ON DELETE RESTRICT;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
  ALTER TABLE public.logistics_records ADD CONSTRAINT fk_logistics_created_by
    FOREIGN KEY (created_by_user_id) REFERENCES public.users(id) ON DELETE RESTRICT;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
CREATE UNIQUE INDEX IF NOT EXISTS ux_logistics_sales_order
    ON public.logistics_records (sales_order_id) WHERE sales_order_id IS NOT NULL;

ALTER TABLE public.warranties ADD COLUMN IF NOT EXISTS sales_order_id BIGINT;
ALTER TABLE public.warranties ADD COLUMN IF NOT EXISTS commercial_customer_id BIGINT;
ALTER TABLE public.warranties ADD COLUMN IF NOT EXISTS created_by_user_id BIGINT;
ALTER TABLE public.warranties ALTER COLUMN customer_id DROP NOT NULL;
DO $$ BEGIN
  ALTER TABLE public.warranties ADD CONSTRAINT fk_warranties_sales_order
    FOREIGN KEY (sales_order_id) REFERENCES public.sales_orders(id) ON DELETE RESTRICT;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
  ALTER TABLE public.warranties ADD CONSTRAINT fk_warranties_commercial_customer
    FOREIGN KEY (commercial_customer_id) REFERENCES public.customers(id) ON DELETE RESTRICT;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
  ALTER TABLE public.warranties ADD CONSTRAINT fk_warranties_created_by
    FOREIGN KEY (created_by_user_id) REFERENCES public.users(id) ON DELETE RESTRICT;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

ALTER TABLE public.refunds ADD COLUMN IF NOT EXISTS requested_by_user_id BIGINT;
DO $$ BEGIN
  ALTER TABLE public.refunds ADD CONSTRAINT fk_refunds_requested_by
    FOREIGN KEY (requested_by_user_id) REFERENCES public.users(id) ON DELETE RESTRICT;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

CREATE TABLE IF NOT EXISTS public.quote_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_id BIGINT NOT NULL REFERENCES public.quotes(id) ON DELETE RESTRICT,
    actor_user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    event_type VARCHAR(30) NOT NULL CHECK (event_type IN ('CREATED', 'ACCEPTED', 'REJECTED', 'CANCELLED', 'EXPIRED', 'PAYMENT_CONFIRMED')),
    changed_fields JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_quote_audit_quote_date
    ON public.quote_audit_events (quote_id, created_at, id);

ALTER TABLE public.inventory_movements ALTER COLUMN purchase_receipt_item_id DROP NOT NULL;
ALTER TABLE public.inventory_movements ADD COLUMN IF NOT EXISTS sales_order_item_id BIGINT;
DO $$ BEGIN
  ALTER TABLE public.inventory_movements ADD CONSTRAINT fk_inventory_movements_sales_order_item
    FOREIGN KEY (sales_order_item_id) REFERENCES public.sales_order_items(id) ON DELETE RESTRICT;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
ALTER TABLE public.inventory_movements DROP CONSTRAINT IF EXISTS inventory_movements_movement_type_check;
ALTER TABLE public.inventory_movements DROP CONSTRAINT IF EXISTS inventory_movements_quantity_delta_check;
DO $$ BEGIN
  ALTER TABLE public.inventory_movements ADD CONSTRAINT chk_inventory_movements_origin_xor
    CHECK ((purchase_receipt_item_id IS NOT NULL) <> (sales_order_item_id IS NOT NULL));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
  ALTER TABLE public.inventory_movements ADD CONSTRAINT chk_inventory_movements_type_origin
    CHECK ((movement_type = 'PURCHASE_RECEIPT' AND purchase_receipt_item_id IS NOT NULL AND quantity_delta > 0)
        OR (movement_type = 'SALE' AND sales_order_item_id IS NOT NULL AND quantity_delta < 0));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
  ALTER TABLE public.inventory_movements ADD CONSTRAINT chk_inventory_movements_nonzero_delta
    CHECK (quantity_delta <> 0);
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
  ALTER TABLE public.inventory_movements ADD CONSTRAINT chk_inventory_movements_stock_after
    CHECK (stock_after = stock_before + quantity_delta AND stock_after >= 0);
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
CREATE UNIQUE INDEX IF NOT EXISTS ux_inventory_movements_sales_item
    ON public.inventory_movements (sales_order_item_id) WHERE sales_order_item_id IS NOT NULL;

COMMIT;
