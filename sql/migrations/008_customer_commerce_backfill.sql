-- Backfill repetible de identities históricas a customers. No fusiona por correo/teléfono.
-- Ejecutar en una copia restaurada y revisar customer_commerce_migration_issues.
BEGIN;

CREATE TABLE IF NOT EXISTS public.customer_commerce_migration_map (
    source_entity VARCHAR(40) NOT NULL,
    source_id BIGINT NOT NULL,
    customer_id BIGINT NOT NULL REFERENCES public.customers(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (source_entity, source_id)
);
CREATE TABLE IF NOT EXISTS public.customer_commerce_migration_issues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_entity VARCHAR(40) NOT NULL,
    source_id BIGINT NOT NULL,
    issue_code VARCHAR(50) NOT NULL,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMPTZ,
    UNIQUE (source_entity, source_id, issue_code)
);

-- One commercial profile per legacy portal user referenced by business records.
INSERT INTO public.customers (display_name, phone, email, origin, user_id)
SELECT LEFT(BTRIM(CONCAT_WS(' ', NULLIF(BTRIM(u.name), ''), NULLIF(BTRIM(u.last_name), ''))), 200),
       BTRIM(u.phone), NULLIF(LOWER(BTRIM(u.email)), ''), 'PORTAL', u.id
FROM public.users u
WHERE u.role::text = 'CUSTOMER'
  AND (EXISTS (SELECT 1 FROM public.tickets t WHERE t.customer_id=u.id)
       OR EXISTS (SELECT 1 FROM public.payments p WHERE p.customer_id=u.id)
       OR EXISTS (SELECT 1 FROM public.warranties w WHERE w.customer_id=u.id)
       OR EXISTS (SELECT 1 FROM public.logistics_records l JOIN public.tickets t ON t.id=l.ticket_id WHERE t.customer_id=u.id))
  AND length(BTRIM(COALESCE(u.phone,''))) BETWEEN 7 AND 30
  AND length(BTRIM(CONCAT_WS(' ', NULLIF(BTRIM(u.name), ''), NULLIF(BTRIM(u.last_name), '')))) BETWEEN 2 AND 200
ON CONFLICT (user_id) DO NOTHING;

INSERT INTO public.customer_commerce_migration_map (source_entity, source_id, customer_id)
SELECT 'users', u.id, c.id FROM public.users u JOIN public.customers c ON c.user_id=u.id
ON CONFLICT (source_entity, source_id) DO NOTHING;

INSERT INTO public.customer_commerce_migration_issues(source_entity,source_id,issue_code,details)
SELECT 'users',u.id,'MISSING_REQUIRED_CONTACT',jsonb_build_object('has_phone',u.phone IS NOT NULL,'has_name',u.name IS NOT NULL)
FROM public.users u
WHERE u.role::text='CUSTOMER'
  AND (EXISTS (SELECT 1 FROM public.tickets t WHERE t.customer_id=u.id)
       OR EXISTS (SELECT 1 FROM public.payments p WHERE p.customer_id=u.id)
       OR EXISTS (SELECT 1 FROM public.warranties w WHERE w.customer_id=u.id))
  AND (length(BTRIM(COALESCE(u.phone,''))) NOT BETWEEN 7 AND 30
       OR length(BTRIM(CONCAT_WS(' ', NULLIF(BTRIM(u.name), ''), NULLIF(BTRIM(u.last_name), '')))) NOT BETWEEN 2 AND 200)
ON CONFLICT (source_entity,source_id,issue_code) DO NOTHING;

-- Manual records get an individual customer per ticket, regardless of contact matches.
WITH candidates AS (
  SELECT t.id AS ticket_id, nextval(pg_get_serial_sequence('public.customers','id')) AS customer_id,
         BTRIM(t.contact_name) AS display_name, BTRIM(t.contact_phone) AS phone,
         NULLIF(LOWER(BTRIM(t.contact_email)), '') AS email, t.created_by_user_id
  FROM public.tickets t
  WHERE t.commercial_customer_id IS NULL AND t.customer_id IS NULL
    AND length(BTRIM(COALESCE(t.contact_name,''))) BETWEEN 2 AND 200
    AND length(BTRIM(COALESCE(t.contact_phone,''))) BETWEEN 7 AND 30
    AND NOT EXISTS (SELECT 1 FROM public.customer_commerce_migration_map m
                    WHERE m.source_entity='manual_ticket' AND m.source_id=t.id)
), inserted AS (
  INSERT INTO public.customers(id,display_name,phone,email,origin,created_by_user_id)
  SELECT customer_id,display_name,phone,email,'MANUAL',created_by_user_id FROM candidates
  RETURNING id
)
INSERT INTO public.customer_commerce_migration_map(source_entity,source_id,customer_id)
SELECT 'manual_ticket',c.ticket_id,c.customer_id FROM candidates c JOIN inserted i ON i.id=c.customer_id;

UPDATE public.tickets t SET commercial_customer_id=m.customer_id
FROM public.customer_commerce_migration_map m
WHERE t.commercial_customer_id IS NULL AND (
  (t.customer_id IS NOT NULL AND m.source_entity='users' AND m.source_id=t.customer_id)
  OR (t.customer_id IS NULL AND m.source_entity='manual_ticket' AND m.source_id=t.id)
);

INSERT INTO public.customer_commerce_migration_issues(source_entity,source_id,issue_code,details)
SELECT 'tickets',t.id,'UNRESOLVED_CUSTOMER',jsonb_build_object('legacy_user_id',t.customer_id,'contact_name',t.contact_name,'contact_phone',t.contact_phone)
FROM public.tickets t WHERE t.commercial_customer_id IS NULL
ON CONFLICT (source_entity,source_id,issue_code) DO NOTHING;

-- Quotes inherit ownership and contact snapshots from their service ticket.
UPDATE public.quotes q SET customer_id=t.commercial_customer_id,
    customer_name_snapshot=COALESCE(q.customer_name_snapshot,t.contact_name,c.display_name),
    customer_phone_snapshot=COALESCE(q.customer_phone_snapshot,t.contact_phone,c.phone),
    customer_email_snapshot=COALESCE(q.customer_email_snapshot,t.contact_email,c.email)
FROM public.tickets t LEFT JOIN public.customers c ON c.id=t.commercial_customer_id
WHERE q.ticket_id=t.id AND q.customer_id IS NULL AND t.commercial_customer_id IS NOT NULL;

-- Payments retain their legacy user FK for the compatibility window and gain commercial ownership.
UPDATE public.payments p SET commercial_customer_id=COALESCE(t.commercial_customer_id,
    (SELECT m.customer_id FROM public.customer_commerce_migration_map m
     WHERE m.source_entity='users' AND m.source_id=p.customer_id))
FROM public.tickets t
WHERE p.commercial_customer_id IS NULL AND p.ticket_id=t.id
  AND (t.commercial_customer_id IS NOT NULL OR EXISTS (SELECT 1 FROM public.customer_commerce_migration_map m
       WHERE m.source_entity='users' AND m.source_id=p.customer_id));
UPDATE public.payments p SET commercial_customer_id=m.customer_id
FROM public.customer_commerce_migration_map m
WHERE p.commercial_customer_id IS NULL AND m.source_entity='users' AND m.source_id=p.customer_id;

UPDATE public.warranties w SET commercial_customer_id=m.customer_id
FROM public.customer_commerce_migration_map m
WHERE w.commercial_customer_id IS NULL AND m.source_entity='users' AND m.source_id=w.customer_id;
UPDATE public.logistics_records l SET commercial_customer_id=t.commercial_customer_id
FROM public.tickets t
WHERE l.ticket_id=t.id AND l.commercial_customer_id IS NULL AND t.commercial_customer_id IS NOT NULL;

INSERT INTO public.customer_commerce_migration_issues(source_entity,source_id,issue_code,details)
SELECT 'quotes',q.id,'UNRESOLVED_CUSTOMER',jsonb_build_object('ticket_id',q.ticket_id)
FROM public.quotes q WHERE q.customer_id IS NULL
ON CONFLICT (source_entity,source_id,issue_code) DO NOTHING;
INSERT INTO public.customer_commerce_migration_issues(source_entity,source_id,issue_code,details)
SELECT 'payments',p.id,'UNRESOLVED_CUSTOMER',jsonb_build_object('ticket_id',p.ticket_id,'legacy_user_id',p.customer_id)
FROM public.payments p WHERE p.commercial_customer_id IS NULL
ON CONFLICT (source_entity,source_id,issue_code) DO NOTHING;

COMMIT;
