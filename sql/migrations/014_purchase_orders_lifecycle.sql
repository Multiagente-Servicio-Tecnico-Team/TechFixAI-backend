-- Purchase-order lifecycle and receipt-before-invoice support.
-- Review the target schema and run the fail-fast preflight before applying.
-- This migration is transactional and never deletes purchase or stock history.
BEGIN;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM public.purchase_orders) THEN
        RAISE EXCEPTION 'Migration 014 stopped: classify and review existing purchase_orders before mapping legacy states.';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM public.supplier_purchases p
        JOIN public.purchase_receipts r ON r.purchase_id = p.id
        WHERE p.purchase_order_id IS NOT NULL
    ) THEN
        RAISE EXCEPTION 'Migration 014 stopped: reconcile invoice receipts already linked to purchase orders before continuing.';
    END IF;
END;
$$;

ALTER TABLE public.purchase_orders
    ALTER COLUMN status SET DEFAULT 'DRAFT',
    ALTER COLUMN total_amount TYPE numeric(14,2),
    ADD COLUMN currency char(3) NOT NULL DEFAULT 'PEN',
    ADD COLUMN notes text,
    ADD COLUMN created_by_user_id bigint NOT NULL,
    ADD COLUMN issued_by_user_id bigint,
    ADD COLUMN issued_at timestamptz,
    ADD COLUMN cancelled_by_user_id bigint,
    ADD COLUMN cancelled_at timestamptz,
    ADD COLUMN cancellation_reason varchar(500);

ALTER TABLE public.purchase_orders
    ADD CONSTRAINT purchase_orders_created_by_user_id_fkey
        FOREIGN KEY (created_by_user_id) REFERENCES public.users(id) ON DELETE RESTRICT,
    ADD CONSTRAINT purchase_orders_issued_by_user_id_fkey
        FOREIGN KEY (issued_by_user_id) REFERENCES public.users(id) ON DELETE RESTRICT,
    ADD CONSTRAINT purchase_orders_cancelled_by_user_id_fkey
        FOREIGN KEY (cancelled_by_user_id) REFERENCES public.users(id) ON DELETE RESTRICT,
    ADD CONSTRAINT chk_purchase_orders_status
        CHECK (status IN ('DRAFT','ISSUED','PARTIALLY_RECEIVED','RECEIVED','CANCELLED')),
    ADD CONSTRAINT chk_purchase_orders_currency
        CHECK (currency = 'PEN'),
    ADD CONSTRAINT chk_purchase_orders_cancel_metadata
        CHECK ((status = 'CANCELLED' AND cancelled_by_user_id IS NOT NULL
                AND cancelled_at IS NOT NULL AND length(btrim(cancellation_reason)) BETWEEN 1 AND 500)
            OR (status <> 'CANCELLED' AND cancelled_by_user_id IS NULL
                AND cancelled_at IS NULL AND cancellation_reason IS NULL)),
    ADD CONSTRAINT chk_purchase_orders_issue_metadata
        CHECK (
            (status IN ('ISSUED','PARTIALLY_RECEIVED','RECEIVED')
                AND issued_by_user_id IS NOT NULL AND issued_at IS NOT NULL) OR
            (status IN ('DRAFT','CANCELLED')
                AND ((issued_by_user_id IS NULL AND issued_at IS NULL)
                    OR (issued_by_user_id IS NOT NULL AND issued_at IS NOT NULL)))
        );

CREATE INDEX ix_purchase_orders_supplier_status_created
    ON public.purchase_orders(supplier_id,status,created_at DESC,id DESC);
CREATE INDEX ix_purchase_orders_status_estimated_arrival
    ON public.purchase_orders(status,estimated_arrival);

ALTER TABLE public.purchase_order_items
    ALTER COLUMN unit_cost TYPE numeric(14,2),
    ALTER COLUMN subtotal TYPE numeric(14,2),
    ADD COLUMN code_snapshot varchar(50),
    ADD COLUMN description_snapshot varchar(300);

UPDATE public.purchase_order_items i
SET code_snapshot = s.code,
    description_snapshot = COALESCE(NULLIF(btrim(i.custom_item_name),''), s.name)
FROM public.spare_parts s
WHERE i.spare_part_id = s.id;

UPDATE public.purchase_order_items i
SET description_snapshot = NULLIF(btrim(i.custom_item_name),'')
WHERE i.description_snapshot IS NULL;

ALTER TABLE public.purchase_order_items
    DROP CONSTRAINT purchase_order_items_purchase_order_id_fkey,
    ADD CONSTRAINT purchase_order_items_purchase_order_id_fkey
        FOREIGN KEY (purchase_order_id) REFERENCES public.purchase_orders(id) ON DELETE RESTRICT,
    ADD CONSTRAINT chk_purchase_order_items_quantity CHECK (quantity > 0),
    ADD CONSTRAINT chk_purchase_order_items_amounts CHECK (unit_cost >= 0 AND subtotal >= 0);

CREATE TABLE public.purchase_order_audit_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id bigint NOT NULL REFERENCES public.purchase_orders(id) ON DELETE RESTRICT,
    actor_user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    event_type varchar(30) NOT NULL CHECK (event_type IN
        ('CREATED','UPDATED','ISSUED','CANCELLED','RECEIPT_CONFIRMED','LEGACY_RECEIPT_RECONCILED')),
    changed_fields jsonb,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_purchase_order_audit_order_created
    ON public.purchase_order_audit_events(purchase_order_id,created_at,id);

CREATE TABLE public.purchase_order_receipts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id bigint NOT NULL REFERENCES public.purchase_orders(id) ON DELETE RESTRICT,
    actor_user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    idempotency_key uuid NOT NULL,
    request_hash char(64) NOT NULL CHECK (request_hash ~ '^[0-9a-f]{64}$'),
    received_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    notes text,
    CONSTRAINT uq_purchase_order_receipt_actor_key
        UNIQUE (purchase_order_id,actor_user_id,idempotency_key)
);
CREATE INDEX ix_purchase_order_receipts_order_date
    ON public.purchase_order_receipts(purchase_order_id,received_at,id);

CREATE TABLE public.purchase_order_receipt_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id bigint NOT NULL REFERENCES public.purchase_order_receipts(id) ON DELETE RESTRICT,
    purchase_order_item_id bigint NOT NULL REFERENCES public.purchase_order_items(id) ON DELETE RESTRICT,
    quantity_received integer NOT NULL CHECK (quantity_received > 0),
    CONSTRAINT uq_purchase_order_receipt_line UNIQUE (receipt_id,purchase_order_item_id)
);
CREATE INDEX ix_purchase_order_receipt_items_order_line
    ON public.purchase_order_receipt_items(purchase_order_item_id,receipt_id);

ALTER TABLE public.supplier_purchase_items
    ADD COLUMN purchase_order_item_id bigint,
    ADD CONSTRAINT supplier_purchase_items_purchase_order_item_id_fkey
        FOREIGN KEY (purchase_order_item_id) REFERENCES public.purchase_order_items(id) ON DELETE RESTRICT;
CREATE INDEX ix_supplier_purchase_items_order_line
    ON public.supplier_purchase_items(purchase_order_item_id)
    WHERE purchase_order_item_id IS NOT NULL;

ALTER TABLE public.inventory_movements
    ADD COLUMN purchase_order_receipt_item_id bigint;
ALTER TABLE public.inventory_movements
    ADD CONSTRAINT inventory_movements_purchase_order_receipt_item_id_fkey
        FOREIGN KEY (purchase_order_receipt_item_id)
        REFERENCES public.purchase_order_receipt_items(id) ON DELETE RESTRICT;
CREATE UNIQUE INDEX uq_inventory_movements_purchase_order_receipt_item
    ON public.inventory_movements(purchase_order_receipt_item_id)
    WHERE purchase_order_receipt_item_id IS NOT NULL;

ALTER TABLE public.inventory_movements
    DROP CONSTRAINT chk_inventory_movements_origin_xor,
    DROP CONSTRAINT chk_inventory_movements_type_origin;
ALTER TABLE public.inventory_movements
    ADD CONSTRAINT chk_inventory_movements_origin_xor
        CHECK (num_nonnulls(purchase_receipt_item_id,purchase_order_receipt_item_id,sales_order_item_id) <= 1),
    ADD CONSTRAINT chk_inventory_movements_type_origin
        CHECK (
            (movement_type = 'PURCHASE_RECEIPT'
                AND num_nonnulls(purchase_receipt_item_id,purchase_order_receipt_item_id) = 1
                AND sales_order_item_id IS NULL AND quantity_delta > 0 AND actor_kind = 'USER') OR
            (movement_type = 'SALE'
                AND sales_order_item_id IS NOT NULL AND purchase_receipt_item_id IS NULL
                AND purchase_order_receipt_item_id IS NULL AND quantity_delta < 0 AND actor_kind = 'USER') OR
            (movement_type = 'ADJUSTMENT_IN'
                AND purchase_receipt_item_id IS NULL AND purchase_order_receipt_item_id IS NULL
                AND sales_order_item_id IS NULL AND quantity_delta > 0 AND actor_kind = 'USER') OR
            (movement_type = 'ADJUSTMENT_OUT'
                AND purchase_receipt_item_id IS NULL AND purchase_order_receipt_item_id IS NULL
                AND sales_order_item_id IS NULL AND quantity_delta < 0 AND actor_kind = 'USER') OR
            (movement_type = 'OPENING_BALANCE'
                AND purchase_receipt_item_id IS NULL AND purchase_order_receipt_item_id IS NULL
                AND sales_order_item_id IS NULL AND actor_kind = 'USER' AND quantity_delta > 0) OR
            (movement_type = 'OPENING_BALANCE'
                AND purchase_receipt_item_id IS NULL AND purchase_order_receipt_item_id IS NULL
                AND sales_order_item_id IS NULL AND actor_kind = 'SYSTEM'
                AND quantity_delta >= 0 AND stock_before = 0)
        );

COMMIT;
