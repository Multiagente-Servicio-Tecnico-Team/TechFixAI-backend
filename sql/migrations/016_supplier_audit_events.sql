-- Track who creates or edits suppliers, including ADMIN chat proposals.
-- Existing supplier rows are preserved; this migration adds audit storage only.
BEGIN;

DO $$
BEGIN
  IF to_regclass('public.suppliers') IS NULL THEN
    RAISE EXCEPTION 'public.suppliers must exist before supplier audit can be installed';
  END IF;
  IF to_regclass('public.users') IS NULL THEN
    RAISE EXCEPTION 'public.users must exist before supplier audit can be installed';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.supplier_audit_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id bigint NOT NULL REFERENCES public.suppliers(id) ON DELETE RESTRICT,
    actor_user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    event_type varchar(20) NOT NULL CHECK (event_type IN ('CREATED', 'UPDATED')),
    changed_fields jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_supplier_audit_events_supplier_created
    ON public.supplier_audit_events (supplier_id, created_at DESC, id DESC);

COMMIT;
